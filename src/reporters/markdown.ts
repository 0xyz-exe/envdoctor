import type { ScanReport } from "../types.js";
import { deepRedact } from "../security/redactor.js";

export function formatMarkdownReport(rawReport: ScanReport): string {
  const report = deepRedact(rawReport);
  const lines: string[] = [];

  lines.push("# 🩺 EnvDoctor Diagnostic Report");
  lines.push("");
  lines.push(`- **Scanned At:** \`${report.scannedAt}\``);
  lines.push(`- **Target Project:** \`${report.projectRoot}\``);
  lines.push(`- **Host Platform:** \`${report.platform} (${report.arch})\``);
  lines.push(`- **Health Score:** **${report.health.score}/100** (\`${report.health.rating.toUpperCase()}\`)`);
  lines.push(`- **Diagnostics Count:** ${report.health.total} checks (${report.health.passed} passed, ${report.health.warning} warnings, ${report.health.failed} failed)`);
  lines.push("");

  lines.push("## Summary");
  lines.push("");
  lines.push("| Category | Total | Passed | Warnings | Failed |");
  lines.push("| :--- | :---: | :---: | :---: | :---: |");
  for (const [cat, stat] of Object.entries(report.categories)) {
    lines.push(`| **${cat}** | ${stat.total} | ${stat.passed} | ${stat.warning} | ${stat.failed} |`);
  }
  lines.push("");

  lines.push("## Diagnostic Findings");
  lines.push("");

  for (const item of report.results) {
    const icon =
      item.status === "passed"
        ? "✅"
        : item.status === "warning"
        ? "⚠️"
        : item.status === "failed"
        ? "❌"
        : "ℹ️";

    lines.push(`### ${icon} ${item.title}`);
    lines.push(`- **Category:** \`${item.category}\` | **Severity:** \`${item.severity}\` | **Status:** \`${item.status}\``);
    lines.push(`- **Summary:** ${item.summary}`);
    if (item.expected) lines.push(`- **Expected:** ${item.expected}`);
    if (item.actual) lines.push(`- **Actual:** \`${item.actual}\``);
    if (item.remediation && item.remediation.length > 0) {
      lines.push("- **Recommended Action:**");
      for (const r of item.remediation) {
        lines.push(`  - ${r}`);
      }
    }
    if (item.documentationUrl) {
      lines.push(`- **Documentation:** [${item.documentationUrl}](${item.documentationUrl})`);
    }
    lines.push("");
  }

  lines.push("---");
  lines.push("*Generated by [EnvDoctor](https://github.com/0xyz-exe/envdoctor) — Developer Environment Configuration Checker.*");

  return lines.join("\n");
}
